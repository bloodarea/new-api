#!/usr/bin/env bash
# Publish the patched source into the GitHub fork, where GitHub Actions builds
# it (see ci/build-image.yml).
#
# The fork is used as the CI host because GitHub Actions only runs on GitHub
# repositories, and this deploy repo lives on our own Gitea. Two things are
# written to the fork:
#
#   main              + .github/workflows/build-image.yml, so the "Run workflow"
#                       button exists (GitHub only lists workflows from the
#                       default branch); main stays otherwise a mirror of
#                       upstream, which keeps future upstream merges clean.
#   deploy/<tag>      upstream tag + patches/0[12] + VERSION + deploy/Dockerfile
#                       + the same workflow, i.e. exactly the tree CI builds.
#
# 03-docker-mirror.patch is skipped on purpose: it exists to make a China build
# host faster, and the GitHub runner is not one.
#
# Usage:  FORK_CLONE=~/src/new-api ./fork-branch.sh
# The clone must be clean; this script resets its main and deploy branch.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FORK_CLONE="${FORK_CLONE:-$ROOT/../new-api}"
FORK_REMOTE="${FORK_REMOTE:-origin}"
UPSTREAM_URL="${UPSTREAM_URL:-https://github.com/QuantumNous/new-api.git}"
UPSTREAM_TAG="${UPSTREAM_TAG:-v1.0.0-rc.41}"
BRANCH="${BRANCH:-deploy/rc.41}"
PUSH="${PUSH:-1}"

die() { echo "!!! $*" >&2; exit 1; }

[ -d "$FORK_CLONE/.git" ] || die "FORK_CLONE=$FORK_CLONE is not a git clone of the fork"
[ -f "$ROOT/ci/build-image.yml" ] || die "ci/build-image.yml is missing"
[ -f "$ROOT/deploy/Dockerfile" ] || die "deploy/Dockerfile is missing"

cd "$FORK_CLONE"
[ -z "$(git status --porcelain)" ] || die "$FORK_CLONE has uncommitted changes; commit or stash them first"

# Commit identity: reuse the clone's, fall back to something neutral.
identity=()
[ -n "$(git config user.email || true)" ] || identity=(-c user.name="new-api-deploy" -c user.email="new-api-deploy@localhost")

echo "==> fetching $UPSTREAM_TAG from upstream and $FORK_REMOTE"
git fetch --quiet "$UPSTREAM_URL" "refs/tags/$UPSTREAM_TAG:refs/tags/$UPSTREAM_TAG" --force
git fetch --quiet "$FORK_REMOTE"

# --- default branch: carry the workflow so the Run button exists -------------
echo "==> updating the default branch with the workflow"
git switch --quiet -C main "$FORK_REMOTE/main"
mkdir -p .github/workflows
cp "$ROOT/ci/build-image.yml" .github/workflows/build-image.yml
git add .github/workflows/build-image.yml
if git diff --cached --quiet; then
  echo "    workflow already up to date on main"
else
  git "${identity[@]}" commit --quiet -m "ci: build the patched image on GitHub Actions"
  echo "    committed workflow to main"
fi

# --- deploy branch: the tree CI actually builds -----------------------------
echo "==> building $BRANCH from $UPSTREAM_TAG"
git switch --quiet -C "$BRANCH" "$UPSTREAM_TAG"
for p in "$ROOT"/patches/0[12]-*.patch; do
  git apply --check "$p" || die "$(basename "$p") does not apply to $UPSTREAM_TAG; rebase it first"
  git apply "$p"
  echo "    applied $(basename "$p")"
done
printf '%s' "$UPSTREAM_TAG" > VERSION
mkdir -p deploy .github/workflows
cp "$ROOT/deploy/Dockerfile" deploy/Dockerfile
cp "$ROOT/ci/build-image.yml" .github/workflows/build-image.yml
git add -A
git "${identity[@]}" commit --quiet -m "deploy: $UPSTREAM_TAG with our patches

Generated by fork-branch.sh from the deploy repo; do not edit by hand.
Contains patches/0[12] (03 is local-mirror only) plus the runtime Dockerfile
and the CI workflow."

echo "==> branch contents"
git log -1 --format='    %h %s'
git diff --stat "$UPSTREAM_TAG" HEAD | tail -3

if [ "$PUSH" != 1 ]; then
  echo "==> PUSH=0: not pushing. Branches are ready locally in $FORK_CLONE"
  exit 0
fi

echo "==> pushing to $FORK_REMOTE"
git push --quiet "$FORK_REMOTE" main
git push --quiet --force-with-lease "$FORK_REMOTE" "$BRANCH"
echo
echo "==> done. Next, once per fork:"
echo "    1. Settings -> Actions -> allow workflows"
echo "    2. Actions -> Build patched image -> Run workflow"
echo "    The image lands in ghcr.io/<owner>/new-api (private on first push;"
echo "    make the package public if the deploy host pulls anonymously)."
